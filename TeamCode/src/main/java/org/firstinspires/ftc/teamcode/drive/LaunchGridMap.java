package org.firstinspires.ftc.teamcode.drive;

import org.firstinspires.ftc.teamcode.subsystems.HiveTarget;

import java.util.Locale;

/**
 * The 2-D launch map (branch launch-grid-2d, 2026-11-12): the flywheel speed and the aim for a launch from ANYWHERE on the field, from the robot's position and the cell it aims at,
 * instead of the speed from the distance alone ({@link org.firstinspires.ftc.teamcode.subsystems.LaunchMap}) and the geometric aim of {@link TargetLock#aimHeadingRad}. While the 2-D
 * method is on, THIS is the only source: it always gives a speed and an aim (it never hands back to the formula). Pure Java (no hardware): it compiles on a PC
 * (tools/launchgrid/GridMapCheck.java).
 *
 * The data ({@link LaunchGridData}, generated by tools/launchgrid/make_table.py) is a set of spots, each with the flywheel speed that scored, the aim RESIDUAL (the heading that scored
 * minus the bearing from the robot to the cell's center, degrees: the aim is bearing + residual), whether a shot is possible there and whether the spot was MEASURED or ESTIMATED
 * (the launching spots nobody measured, filled in from the nearest measured spots), triangulated.
 *
 * Lookup:
 *  - inside a triangle of spots: the speed and the residual are blended linearly (a no-shot spot does not contribute to the blend);
 *  - outside the spots: the value at the nearest point of the outline is held (the estimated spots already reach the walls, so this is a few inches);
 *  - a spot, or a point whose nearest spot, had no shot possible is a NO_SHOT zone: the answer is still a speed and an aim (the nearest good spots'), and the zone is the WARNING
 *    (the screen shows NO SHOT ZONE), because the grid says a salvo from there does not score.
 * {@link Zone#NO_DATA} only happens when a cell has no data at all.
 *
 * The cells: BLUE_REAR is measured, BLUE_AUDIENCE is a SEED (the measured spots mirrored about X = 0 keeping the ball's path, see make_table.py) until it is measured, and the RED cells
 * are the blue data turned 180 degrees about the field center (the residual does not change under the turn).
 */
public final class LaunchGridMap {

    public enum Zone { INTERPOLATED, EXTRAPOLATED, NO_SHOT, NO_DATA }

    /** One lookup. speed and residualDeg are NaN only for NO_DATA. */
    public static final class Result {
        public final Zone zone;
        public final double speed;
        public final double residualDeg;
        public final boolean seeded;
        public final boolean rotated;
        /** True when the answer rests on an estimated spot or was held from the outline (not on measured spots alone). */
        public final boolean estimated;
        public final String note;

        Result(Zone zone, double speed, double residualDeg, boolean seeded, boolean rotated, boolean estimated, String note) {
            this.zone = zone;
            this.speed = speed;
            this.residualDeg = residualDeg;
            this.seeded = seeded;
            this.rotated = rotated;
            this.estimated = estimated;
            this.note = note;
        }

        /** True when there is a speed and an aim residual to use (every zone but NO_DATA). */
        public boolean hasValues() {
            return !Double.isNaN(speed) && !Double.isNaN(residualDeg);
        }

        public String describe() {
            String tags = (seeded ? " (SEEDED)" : "") + (rotated ? " (rotated)" : "") + (estimated ? " (estimated)" : "");
            if (hasValues()) {
                return String.format(Locale.US, "%s%s: speed %.0f ticks/s, aim residual %+.1f deg%s", zone, tags, speed, residualDeg, note.isEmpty() ? "" : " [" + note + "]");
            }
            return String.format(Locale.US, "%s%s: %s", zone, tags, note);
        }
    }

    private static final class Data {
        final double[][] spots;
        final int[][] tris;
        final boolean seeded;
        final double[][] hull;

        Data(double[][] spots, int[][] tris, boolean seeded) {
            this.spots = spots;
            this.tris = tris;
            this.seeded = seeded;
            this.hull = spots.length >= 3 ? convexHull(spots) : new double[0][];
        }
    }

    private static final Data BLUE_REAR = new Data(LaunchGridData.BLUE_REAR, LaunchGridData.BLUE_REAR_TRI, false);
    private static final Data BLUE_AUDIENCE = new Data(LaunchGridData.BLUE_AUDIENCE, LaunchGridData.BLUE_AUDIENCE_TRI, true);

    private LaunchGridMap() {}

    /** The speed and aim for a launch at {@code cell} from (x, y) (field frame, inches). */
    public static Result lookup(HiveTarget cell, double x, double y) {
        switch (cell) {
            case BLUE_REAR:
                return eval(BLUE_REAR, x, y, false);
            case BLUE_AUDIENCE:
                return eval(BLUE_AUDIENCE, x, y, false);
            case RED_AUDIENCE:
                return eval(BLUE_REAR, -x, -y, true);
            default:   // RED_REAR
                return eval(BLUE_AUDIENCE, -x, -y, true);
        }
    }

    private static Result eval(Data d, double x, double y, boolean rotated) {
        if (d.hull.length == 0) return new Result(Zone.NO_DATA, Double.NaN, Double.NaN, d.seeded, rotated, false, "the cell has no grid data");
        // inside a triangle
        for (int[] t : d.tris) {
            double[] w = barycentric(d, t, x, y);
            if (w != null && w[0] >= -1e-9 && w[1] >= -1e-9 && w[2] >= -1e-9) return resolve(d, t, w, x, y, Zone.INTERPOLATED, rotated, false);
        }
        // outside: hold the value at the nearest point of the outline of the spots
        double bestDist = Double.MAX_VALUE, px = 0.0, py = 0.0;
        double[][] h = d.hull;
        for (int i = 0; i < h.length; i++) {
            double ax = h[i][0], ay = h[i][1], bx = h[(i + 1) % h.length][0], by = h[(i + 1) % h.length][1];
            double ex = bx - ax, ey = by - ay;
            double len2 = ex * ex + ey * ey;
            double s = len2 < 1e-12 ? 0.0 : Math.max(0.0, Math.min(1.0, ((x - ax) * ex + (y - ay) * ey) / len2));
            double qx = ax + s * ex, qy = ay + s * ey;
            double dist = Math.hypot(x - qx, y - qy);
            if (dist < bestDist) {
                bestDist = dist;
                px = qx;
                py = qy;
            }
        }
        return atEdge(d, px, py, x, y, rotated, bestDist);
    }

    /** The value at a point on the outline of the spots (it lies on an edge of a triangle), held for a query outside. */
    private static Result atEdge(Data d, double px, double py, double qx, double qy, boolean rotated, double outsideBy) {
        double bestMin = -Double.MAX_VALUE;
        int[] bestT = null;
        double[] bestW = null;
        for (int[] t : d.tris) {
            double[] w = barycentric(d, t, px, py);
            if (w == null) continue;
            double m = Math.min(w[0], Math.min(w[1], w[2]));
            if (m > bestMin) {
                bestMin = m;
                bestT = t;
                bestW = w;
            }
        }
        if (bestT == null) return new Result(Zone.NO_DATA, Double.NaN, Double.NaN, d.seeded, rotated, false, "no triangle");
        // the point is on the outline: clamp the weights into the triangle
        double[] w = {Math.max(0.0, bestW[0]), Math.max(0.0, bestW[1]), Math.max(0.0, bestW[2])};
        double sum = w[0] + w[1] + w[2];
        for (int i = 0; i < 3; i++) w[i] /= sum;
        Result r = resolve(d, bestT, w, qx, qy, Zone.EXTRAPOLATED, rotated, true);
        return new Result(r.zone, r.speed, r.residualDeg, r.seeded, r.rotated, true, String.format(Locale.US, "%.1f in outside the spots, nearest edge held", outsideBy));
    }

    /** Spot column: 0 x, 1 y, 2 speed, 3 residual, 4 status (1 a shot works), 5 estimated. */
    private static Result resolve(Data d, int[] t, double[] w, double qx, double qy, Zone zone, boolean rotated, boolean held) {
        int dominant = 0;
        for (int i = 1; i < 3; i++) if (w[i] > w[dominant]) dominant = i;
        boolean noShot = d.spots[t[dominant]][4] < 0.5;
        double ws = 0.0, speed = 0.0, resid = 0.0;
        boolean est = held;
        for (int i = 0; i < 3; i++) {
            double[] s = d.spots[t[i]];
            if (s[4] < 0.5) continue;
            ws += w[i];
            speed += w[i] * s[2];
            resid += w[i] * s[3];
            if (w[i] > 1e-9 && s[5] > 0.5) est = true;
        }
        if (ws <= 1e-9) {
            // no good spot in the triangle: the nearest good spot's values
            double[] g = nearestGood(d, qx, qy);
            if (g == null) return new Result(Zone.NO_DATA, Double.NaN, Double.NaN, d.seeded, rotated, false, "no good spot in the cell's data");
            return new Result(Zone.NO_SHOT, g[2], g[3], d.seeded, rotated, true, "no shot here; the nearest good spot's values");
        }
        Zone z = noShot ? Zone.NO_SHOT : zone;
        return new Result(z, speed / ws, resid / ws, d.seeded, rotated, est, noShot ? "no shot here; the nearby good spots' values" : "");
    }

    private static double[] nearestGood(Data d, double x, double y) {
        double best = Double.MAX_VALUE;
        double[] g = null;
        for (double[] s : d.spots) {
            if (s[4] < 0.5) continue;
            double dist = Math.hypot(s[0] - x, s[1] - y);
            if (dist < best) {
                best = dist;
                g = s;
            }
        }
        return g;
    }

    private static double[] barycentric(Data d, int[] t, double x, double y) {
        double[] a = d.spots[t[0]], b = d.spots[t[1]], c = d.spots[t[2]];
        double det = (b[1] - c[1]) * (a[0] - c[0]) + (c[0] - b[0]) * (a[1] - c[1]);
        if (Math.abs(det) < 1e-12) return null;
        double l0 = ((b[1] - c[1]) * (x - c[0]) + (c[0] - b[0]) * (y - c[1])) / det;
        double l1 = ((c[1] - a[1]) * (x - c[0]) + (a[0] - c[0]) * (y - c[1])) / det;
        return new double[]{l0, l1, 1.0 - l0 - l1};
    }

    /** Convex hull (counterclockwise) of the spots' x, y. */
    private static double[][] convexHull(double[][] spots) {
        int n = spots.length;
        Integer[] idx = new Integer[n];
        for (int i = 0; i < n; i++) idx[i] = i;
        java.util.Arrays.sort(idx, (p, q) -> spots[p][0] != spots[q][0] ? Double.compare(spots[p][0], spots[q][0]) : Double.compare(spots[p][1], spots[q][1]));
        double[][] hull = new double[2 * n][];
        int k = 0;
        for (int i = 0; i < n; i++) {
            while (k >= 2 && cross(hull[k - 2], hull[k - 1], spots[idx[i]]) <= 0) k--;
            hull[k++] = spots[idx[i]];
        }
        for (int i = n - 2, lower = k + 1; i >= 0; i--) {
            while (k >= lower && cross(hull[k - 2], hull[k - 1], spots[idx[i]]) <= 0) k--;
            hull[k++] = spots[idx[i]];
        }
        return java.util.Arrays.copyOf(hull, k - 1);
    }

    private static double cross(double[] o, double[] a, double[] b) {
        return (a[0] - o[0]) * (b[1] - o[1]) - (a[1] - o[1]) * (b[0] - o[0]);
    }
}
