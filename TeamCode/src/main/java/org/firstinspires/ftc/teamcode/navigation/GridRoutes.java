package org.firstinspires.ftc.teamcode.navigation;

import org.firstinspires.ftc.teamcode.math.Vec;

/**
 * Grid routes (specs/dashes.md section 5): precomputed, time-optimal routes that know about momentum.
 *
 * NOT BUILT in the from-specs rebuild. The routes are generated tables (four route trees and a corner speed table)
 * written by the dash simulator from the fitted drive model. The specs describe what the tables mean but not their
 * layout, and the generator in tools/dash is compiled against the old robot code. So this class only answers
 * "not usable, and why", which is the documented fallback: the dash logs the reason and uses the route planner.
 *
 * The lattice the tables must match is kept here so a later generator and this code can agree on it.
 */
public final class GridRoutes {
    private GridRoutes() { }

    public static final double PITCH_IN = 6.0, HALF_SPAN_IN = 66.0;
    public static final int DIRECTIONS = 16;
    /** Corner angle (deg) to speed limit (in/s). */
    public static final double[][] CORNER_SPEED = {{0, 66}, {10, 60}, {20, 44}, {30, 36}, {45, 24}, {60, 20}};

    /** Null when a table can be used for this blue-frame goal; otherwise the reason it cannot. */
    public static String unusable(Vec blueGoal) {
        return "no grid route tables in this build (they are generated by the dash simulator; see GridRoutes)";
    }
}
